_FALLBACK = "##### #...# #...# #...# #...# #...# #####"

# accent: (bază, semn, unde). Semnele „sus” la majuscule merg în cele 2 rânduri de deasupra; la minuscule
# înlocuiesc primele 2 rânduri ale corpului (libere la a, e; la i se șterge punctul).
_MARKS = {"breve": "#...# .###.", "circ": "..#.. .#.#.", "acute": "...#. ..#..", "grave": ".#... ..#..",
          "comma": "..#.. .#..."}
_COMPOSED = {"Ă": ("A", "breve"), "ă": ("a", "breve"), "Â": ("A", "circ"), "â": ("a", "circ"),
             "Î": ("I", "circ"), "î": ("i", "circ"), "Ș": ("S", "comma"), "ș": ("s", "comma"),
             "Ț": ("T", "comma"), "ț": ("t", "comma"), "É": ("E", "acute"), "È": ("E", "grave"),
             "é": ("e", "acute"), "è": ("e", "grave"), "à": ("a", "grave")}


def _rows(spec):
    return [[c == "#" for c in r] for r in spec.split()]


def glyph(ch):
    """Matrice CELL_H × 5 de bool."""
    cell = [[False] * 5 for _ in range(CELL_H)]
    base, mark = _COMPOSED.get(ch, (ch, None))
    for i, r in enumerate(_rows(_G.get(base, _FALLBACK))):
        cell[TOP + i] = r
    if mark:
        m = _rows(_MARKS[mark])
        if mark == "comma":
            cell[TOP + 7], cell[TOP + 8] = m
        elif base.isupper():
            cell[0], cell[1] = m
        else:
            cell[TOP], cell[TOP + 1] = m
    return cell
